bool is_mark(char32_t c) {
    auto category = utf8proc_category(static_cast<utf8proc_int32_t>(c));
    return category >= UTF8PROC_CATEGORY_MN && category <= UTF8PROC_CATEGORY_ME;
}

bool is_letter_or_digit(char32_t c) {
    auto category = utf8proc_category(static_cast<utf8proc_int32_t>(c));
    return (category >= UTF8PROC_CATEGORY_LU && category <= UTF8PROC_CATEGORY_LO)
           || (category >= UTF8PROC_CATEGORY_ND && category <= UTF8PROC_CATEGORY_NO);
}

char32_t to_lower(char32_t c) {
    return static_cast<char32_t>(utf8proc_tolower(static_cast<utf8proc_int32_t>(c)));
}

size_t decompose(char32_t c, char32_t* out, size_t capacity) {
    int boundclass = 0;
    auto count = utf8proc_decompose_char(static_cast<utf8proc_int32_t>(c), reinterpret_cast<utf8proc_int32_t*>(out),
                                         static_cast<utf8proc_ssize_t>(capacity), UTF8PROC_DECOMPOSE, &boundclass);
    if (count < 0 || static_cast<size_t>(count) > capacity) {
        out[0] = c;
        return 1;
    }
    return static_cast<size_t>(count);
}

std::string to_upper(char32_t c) {
    std::string out;
    auto special = std::find_if(std::begin(SPECIAL_UPPER), std::end(SPECIAL_UPPER),
                                [c](const SpecialUpper& entry) { return entry.code_point == c; });
    if (special != std::end(SPECIAL_UPPER)) {
        for (char32_t upper : special->upper)
            if (upper != 0) utf8::append(out, upper);
    } else {
        utf8::append(out, static_cast<char32_t>(utf8proc_toupper(static_cast<utf8proc_int32_t>(c))));
    }
    return out;
}

